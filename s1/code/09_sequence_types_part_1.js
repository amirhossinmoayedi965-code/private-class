// Array

// آرایه برای نگه داشتن چند مقدار در یک متغیر استفاده می‌شود.
let cars = ["BMW", "Benz", "Porsche"];

console.log(cars);

// گرفتن یک مقدار از آرایه
console.log(cars[0]);
console.log(cars[1]);

// push یک مقدار جدید به آخر آرایه اضافه می‌کند.
cars.push("Toyota");

console.log(cars);

// برای اضافه کردن چند مقدار جدید می‌توانیم از push استفاده کنیم.
cars.push("Ford", "Nissan");

console.log(cars);
