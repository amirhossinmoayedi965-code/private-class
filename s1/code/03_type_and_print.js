// درس 3: typeof و console.log

// console.log برای نمایش دادن مقدارها در خروجی استفاده می‌شود.
console.log("Hello JavaScript");
console.log("My name is Ali");
console.log(20);

// می‌توانیم چند مقدار را با یک console.log نمایش بدهیم.
let studentName = "Sara";
let studentAge = 16;

console.log("Student name:", studentName);
console.log("Student age:", studentAge);

// typeof نوع یک مقدار یا متغیر را به ما نشان می‌دهد.
let name = "Ahmadreza";
let score = 18;
let average = 17.5;
let isPassed = true;

console.log(typeof name);
console.log(typeof score);
console.log(typeof average);
console.log(typeof isPassed);

// خروجی typeof کمک می‌کند بفهمیم JavaScript مقدار را چه چیزی تشخیص داده است.
let numberText = "123";
let realNumber = 123;

console.log(typeof numberText);
console.log(typeof realNumber);
